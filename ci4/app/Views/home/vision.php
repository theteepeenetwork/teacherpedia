            <p>Welcome to Teacherpedia. I've been teaching in the North East of England for the last 8 years. Like many, many teachers out there, I spend a great deal of time making my own resources.</p>
            <p>With some resources, I found myself making the same thing over and over. Same subjects, different questions. Having learned how to code, I decided to use it to make resources that would make my life easier. So I made some resources that saved me hours of time each week, I decided to start sharing them and Teacherpedia was born.</p>


