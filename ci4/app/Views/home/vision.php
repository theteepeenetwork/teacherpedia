                <h2>How are we different?</h2>
                <p>Resources only scratch the surface of what I want to achieve with Teacherpedia. Resources are still very static. While they work, they're inefficient. </p>
                <p>Schools are evolving all the time, but in many ways they are stuck. Learning in school should be dynamic, interesting, relevant and authentic to the learners. We don’t always have the time to ensure this and resources aren’t always valuable to the learner. Therefore, to make resources relevant they should be easy to customise, differentiate and personalise. </p>
