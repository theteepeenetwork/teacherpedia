            <p class="card-text"><img id="different-header" src="https://res.cloudinary.com/teacherpedia/image/upload/v1598875771/branding/doitdifferently2_e1txxu.png" /></p>
            <p>Teachers are brilliant, awesome, visionary people who should be celebrated and rewarded for their hard work. They have created a vibrant community who share incredible resources and practice. However, there is an increasing shift towards these community resources being on a marketplace. It is my firm belief that you shouldn't need to pay out of your own pocket for your profession. Good quality, useful and innovative resources should be readily available. If you have to pay, they should be at the best possible value for teachers. A marketplace is not the best value. </p>
            <p>Having paid for resources that looked brilliant in an effort to save time, I found I was often buying resources that ended up being innappropriate for my lesson. Not only this but this model of sharing resources stifles the community and innovation and the sharing culture. It is open to a market outside the profession, possibly with little knowledge of the curriculum. It also suggests that teachers <i>should</i> be spending their own money on resources. While this is sometimes unavoidable, a model of purchasing individual resources does not provide the best value for teachers. Should teachers choose to pay for resources, they should be provided access to a wide range of resources that can be easily accessed and evaluated and it should be at the best value possible.</p>
